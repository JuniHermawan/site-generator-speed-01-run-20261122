// Line classifiers below are hand-rolled (no per-line regexes): the block loop
// runs them on every line of every body.

/** Only spaces/tabs (or empty): the BLANK test, without a regex. */
function isBlank(line) {
  if (line === '') return true;
  for (let i = 0; i < line.length; i++) {
    const c = line[i];
    if (c !== ' ' && c !== '\t') return false;
  }
  return true;
}

/** Whether `line` is only spaces/tabs after position `from`. */
function onlySpaceTab(line, from) {
  for (let i = from; i < line.length; i++) {
    const c = line[i];
    if (c !== ' ' && c !== '\t') return false;
  }
  return true;
}

function isLangChar(c) {
  return (c >= 'A' && c <= 'Z') || (c >= 'a' && c <= 'z') || (c >= '0' && c <= '9') || c === '_' || c === '+' || c === '-';
}

/** A fence-open line's language, or null (FENCE_OPEN, manual). */
function fenceOpenOf(line) {
  if (!line.startsWith('```')) return null;
  let i = 3;
  while (i < line.length && isLangChar(line[i])) i++;
  if (!onlySpaceTab(line, i)) return null;
  return line.slice(3, i);
}

/** A fence-close line (FENCE_CLOSE, manual). */
function isFenceClose(line) {
  return line.startsWith('```') && onlySpaceTab(line, 3);
}

/** A heading line's level and text, or null (HEADING, manual). */
function headingOf(line) {
  let h = 0;
  while (h < line.length && line[h] === '#') h++;
  if (h === 0 || h > 6) return null;
  if (line[h] !== ' ' && line[h] !== '\t') return null;
  let i = h;
  while (i < line.length && (line[i] === ' ' || line[i] === '\t')) i++;
  let end = line.length;
  while (end > i && (line[end - 1] === ' ' || line[end - 1] === '\t')) end--;
  if (end === i) return null;
  return { depth: h, text: line.slice(i, end) };
}

/** A thematic-break line (HR, manual). */
function isHr(line) {
  if (!line.startsWith('---') && !line.startsWith('***')) return false;
  return onlySpaceTab(line, 3);
}

/** A bullet-list line's item text, or null (BULLET, manual). */
function bulletOf(line) {
  if ((line[0] === '-' || line[0] === '*') && line[1] === ' ') return line.slice(2);
  return null;
}

/** An ordered-list line's number and item text, or null (ORDERED, manual). */
function orderedOf(line) {
  let d = 0;
  while (d < line.length && line[d] >= '0' && line[d] <= '9') d++;
  if (d === 0 || d > 9) return null;
  if (line[d] !== '.' || line[d + 1] !== ' ') return null;
  return { num: Number(line.slice(0, d)), text: line.slice(d + 2) };
}

/** A list-continuation line (CONTINUED, manual): >=2 spaces then a non-space. */
function isContinued(line) {
  if (line[0] !== ' ' || line[1] !== ' ') return false;
  if (line.length <= 2) return false;
  const c = line[2];
  return c !== ' ' && c !== '\t' && c !== '\n' && c !== '\v' && c !== '\f' && c !== '\r';
}

/** Whether `line` ends a paragraph: a blank line, a fence, a heading or a thematic break. */
function endsParagraph(line) {
  return isBlank(line) || fenceOpenOf(line) !== null || headingOf(line) !== null || isHr(line);
}

/** A paragraph line as it is rendered: spaces and tabs at either end dropped. */
const trimLine = (line) => {
  let a = 0;
  let b = line.length;
  while (a < b && (line[a] === ' ' || line[a] === '\t')) a++;
  while (b > a && (line[b - 1] === ' ' || line[b - 1] === '\t')) b--;
  return a === 0 && b === line.length ? line : line.slice(a, b);
};

const ESCAPABLE = new Set(['\\', '`', '*', '_', '[', ']', '(', ')', '#', '+', '-', '.', '!', '>']);

function findUnescaped(s, what, from) {
  for (let j = from; j <= s.length - what.length; j++) {
    if (s[j] === '\\' && j + 1 < s.length && ESCAPABLE.has(s[j + 1])) {
      j++;
      continue;
    }
    if (s.startsWith(what, j)) return j;
  }
  return -1;
}

function findSingleStar(s, from) {
  for (let j = from; j < s.length; j++) {
    const c = s[j];
    if (c === '\\' && j + 1 < s.length && ESCAPABLE.has(s[j + 1])) {
      j++;
      continue;
    }
    if (c !== '*') continue;
    if (s[j + 1] === '*') {
      j++;
      continue;
    }
    return j;
  }
  return -1;
}

/** Any character that can change inline output (a construct or an escapable). */
const INLINE_SPECIAL = /[\\`*\[<&>"']/;
/** Construct starters: backslash, backtick, star, bracket. */
const CONSTRUCT = /[\\`*\[]/g;

/**
 * `s` rendered inline. Same recursion/closer semantics as the reference, but
 * the scan jumps natively to the next construct starter instead of stepping
 * per character, and plain runs are sliced and escaped in one pass.
 */
export function inline(s, env) {
  if (!INLINE_SPECIAL.test(s)) return s;
  const out = [];
  let run = 0; // start of the current plain run in `s`
  let i = 0;
  while (i < s.length) {
    CONSTRUCT.lastIndex = i;
    const m = CONSTRUCT.exec(s);
    const j = m === null ? s.length : m.index;
    if (j === s.length) break;
    const c = s[j];
    if (c === '\\' && j + 1 < s.length && ESCAPABLE.has(s[j + 1])) {
      if (j > run) out.push(escapeHtml(s.slice(run, j)));
      out.push(escapeHtml(s[j + 1]));
      i = j + 2;
      run = i;
      continue;
    }
    if (c === '`') {
      const k = s.indexOf('`', j + 1);
      if (k > j + 1) {
        if (j > run) out.push(escapeHtml(s.slice(run, j)));
        out.push('<code>', escapeHtml(s.slice(j + 1, k)), '</code>');
        i = k + 1;
        run = i;
      } else {
        i = j + 1;
      }
      continue;
    }
    if (c === '*') {
      if (s[j + 1] === '*') {
        const k = findUnescaped(s, '**', j + 2);
        if (k > j + 2) {
          if (j > run) out.push(escapeHtml(s.slice(run, j)));
          out.push('<strong>', inline(s.slice(j + 2, k), env), '</strong>');
          i = k + 2;
          run = i;
        } else {
          i = j + 2;
        }
        continue;
      }
      const k = findSingleStar(s, j + 1);
      if (k > j + 1) {
        if (j > run) out.push(escapeHtml(s.slice(run, j)));
        out.push('<em>', inline(s.slice(j + 1, k), env), '</em>');
        i = k + 1;
        run = i;
      } else {
        i = j + 1;
      }
      continue;
    }
    if (c === '[') {
      const k = findUnescaped(s, ']', j + 1);
      const m2 = k !== -1 && s[k + 1] === '(' ? s.indexOf(')', k + 2) : -1;
      const target = m2 === -1 ? '' : s.slice(k + 2, m2);
      if (target !== '' && !/\s/.test(target)) {
        if (j > run) out.push(escapeHtml(s.slice(run, j)));
        out.push('<a href="', escapeHtml(env.link(target)), '">', inline(s.slice(j + 1, k), env), '</a>');
        i = m2 + 1;
        run = i;
        continue;
      }
    }
    // A backslash with nothing escapable after it, or a '[' that is no link:
    // both stay in the plain run; keep scanning after the character.
    i = j + 1;
  }
  if (s.length > run) out.push(escapeHtml(s.slice(run)));
  return out.join('');
}

/**
 * `src` rendered: HTML, table of contents (level 2/3 headings) and excerpt.
 * Lexing and rendering are fused: no token array, blocks go straight to output.
 */
export function renderMarkdown(src, env) {
  const lines = src.split('\n');
  const ids = new Set();
  const blocks = [];
  const toc = [];
  let excerpt = null;
  let i = 0;
  while (i < lines.length) {
    const line = lines[i];
    if (isBlank(line)) {
      i++;
      continue;
    }
    const lang = fenceOpenOf(line);
    if (lang !== null) {
      const body = [];
      i++;
      while (i < lines.length && !isFenceClose(lines[i])) body.push(lines[i++]);
      i++;
      const cls = lang === '' ? '' : ` class="language-${escapeHtml(lang)}"`;
      blocks.push(`<pre><code${cls}>${body.map((l) => `${escapeHtml(l)}\n`).join('')}</code></pre>\n`);
      continue;
    }
    const heading = headingOf(line);
    if (heading !== null) {
      const id = uniqueSlug(slugify(heading.text), ids);
      const html = inline(heading.text, env);
      blocks.push(`<h${heading.depth} id="${id}">${html}</h${heading.depth}>\n`);
      if (heading.depth === 2 || heading.depth === 3) toc.push({ level: heading.depth, id, html });
      i++;
      continue;
    }
    if (isHr(line)) {
      blocks.push('<hr>\n');
      i++;
      continue;
    }
    if (line[0] === '>') {
      const body = [];
      while (i < lines.length && lines[i][0] === '>') {
        const l = lines[i++];
        body.push(l[1] === ' ' ? l.slice(2) : l.slice(1));
      }
      const qlines = body.map(trimLine).filter((l) => l !== '');
      blocks.push(qlines.length === 0 ? '<blockquote>\n</blockquote>\n' : `<blockquote>\n<p>${inline(qlines.join('\n'), env)}</p>\n</blockquote>\n`);
      continue;
    }
    const bulletText = bulletOf(line);
    const ordered = bulletText === null ? orderedOf(line) : null;
    if (bulletText !== null || ordered !== null) {
      const isOrdered = ordered !== null;
      const items = [];
      while (i < lines.length) {
        const cur = lines[i];
        if (isOrdered) {
          const m = orderedOf(cur);
          if (m !== null) {
            items.push([trimLine(m.text)]);
            i++;
            continue;
          }
        } else {
          const m = bulletOf(cur);
          if (m !== null) {
            items.push([trimLine(m)]);
            i++;
            continue;
          }
        }
        if (isContinued(cur)) {
          items[items.length - 1].push(trimLine(cur));
          i++;
        } else break;
      }
      const tag = isOrdered ? 'ol' : 'ul';
      const open = isOrdered && ordered.num !== 1 ? `<ol start="${ordered.num}">` : `<${tag}>`;
      blocks.push(`${open}\n${items.map((parts) => `<li>${inline(parts.join('\n'), env)}</li>\n`).join('')}</${tag}>\n`);
      continue;
    }
    const body = [trimLine(line)];
    i++;
    while (i < lines.length && !endsParagraph(lines[i])) body.push(trimLine(lines[i++]));
    const text = body.join('\n');
    const html = inline(text, env);
    if (excerpt === null) excerpt = html;
    blocks.push(`<p>${html}</p>\n`);
  }
  return { html: blocks.join(''), toc, excerpt: excerpt ?? '' };
}

